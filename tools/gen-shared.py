#!/usr/bin/env python3
"""Generate Screeps.Types, Screeps.Constants and shared-index.md.

Usage: python3 tools/gen-shared.py <project dir> <screeps/docs checkout>/api/source

Inputs: the docs' inheritance markers (types) and the engine's constants table from
the npm package @screeps/common (node_modules/@screeps/common/lib/constants.js),
which is what Screeps itself puts in the global scope. Run `npm install` first.
shared-index.md is pasted into binding-writer.md; regenerate and re-paste together.
"""
import json, os, re, subprocess, sys

DOCS = sys.argv[2]  # path to a checkout of screeps/docs: api/source
OUT = sys.argv[1]
os.makedirs(f"{OUT}/src/Screeps", exist_ok=True)

# ---------------------------------------------------------------- Types
parent = {}
for f in sorted(os.listdir(DOCS)):
    if not f.endswith(".md"):
        continue
    m = re.search(r"\{% page inherited/(\w+)\.md", open(f"{DOCS}/{f}").read())
    if m:
        parent[f[:-3]] = m.group(1)

ABSTRACT = ["RoomObject", "Structure", "OwnedStructure"]
concrete = sorted(t for t in parent if t not in ABSTRACT)

def chain(t):
    out = []
    while t in parent:
        t = parent[t]
        out.append(t)
    return out

OTHER = [  # (type, doc name, description)
    ("Room", "Room", "An object representing the room in which your units and structures are in."),
    ("RoomPosition", "RoomPosition", "An object representing the specified position in the room."),
    ("RoomVisual", "RoomVisual", "Draws visual debug info in a room."),
    ("MapVisual", "MapVisual", "Draws visual debug info on the world map (`Game.map.visual`)."),
    ("RoomTerrain", "Room.Terrain", "Fast access to the static terrain data of a room."),
    ("CostMatrix", "PathFinder.CostMatrix", "Custom navigation cost data for `PathFinder`."),
    ("Store", "Store", "An object that can contain resources in its cargo."),
    ("StructureSpawnSpawning", "StructureSpawn.Spawning", "Details of the creep being spawned currently."),
]

L = []
w = L.append
w("-- | Every Screeps game-object type and the classes that model JS inheritance.")
w("-- | GENERATED by gen-shared.py from screeps/docs; edit the generator, not this file.")
w("module Screeps.Types")
exports = []
for t, _, _ in OTHER:
    exports.append(t)
for t in ABSTRACT + ["AnyCreep"] + concrete:
    exports.append(t)
exports += ["CostMatrix'", "class IsRoomObject", "class IsStructure", "class IsOwnedStructure",
            "class IsCreep", "class HasPos", "class RoomObjectClass", "className",
            "toRoomObject", "toStructure", "toOwnedStructure", "toAnyCreep", "downcast"]
exports = [e for e in exports if e != "CostMatrix'"]
w("  ( " + "\n  , ".join(exports) + "\n  ) where")
w("")
w("import Prelude\n")
w("import Data.Function.Uncurried (Fn2, runFn2)")
w("import Data.Maybe (Maybe(..))")
w("import Type.Proxy (Proxy(..))")
w("import Unsafe.Coerce (unsafeCoerce)")
w("")
w("-- Opaque objects that are not RoomObjects.")
for t, doc, desc in OTHER:
    w(f"-- | {desc}" + (f" Docs: `{doc}`." if doc != t else ""))
    w(f"foreign import data {t} :: Type")
w("")
w("-- Upcast targets. Values of these types come from APIs that return a mix of")
w("-- objects (`FIND_STRUCTURES`, `Tombstone.creep`, ...). Narrow them with `downcast`.")
w("-- | Any object with a position in a room.")
w("foreign import data RoomObject :: Type")
w("-- | Any structure.")
w("foreign import data Structure :: Type")
w("-- | Any structure that has an owner.")
w("foreign import data OwnedStructure :: Type")
w("-- | A `Creep` or a `PowerCreep` (docs: `Creep | PowerCreep`).")
w("foreign import data AnyCreep :: Type")
w("")
w("-- Concrete game objects (all derive from RoomObject).")
for t in concrete:
    w(f"-- | `{t}` (prototype chain: {' -> '.join([t] + chain(t))}).")
    w(f"foreign import data {t} :: Type")
w("")
w("-- | Derives from `RoomObject` in JS. Accepted wherever the docs ask for a RoomObject.")
w("class IsRoomObject :: Type -> Constraint")
w("class IsRoomObject a")
w("")
w("-- | Derives from `Structure` in JS.")
w("class IsStructure :: Type -> Constraint")
w("class IsRoomObject a <= IsStructure a")
w("")
w("-- | Derives from `OwnedStructure` in JS.")
w("class IsOwnedStructure :: Type -> Constraint")
w("class IsStructure a <= IsOwnedStructure a")
w("")
w("-- | `Creep`, `PowerCreep`, or `AnyCreep`. Use for docs types `Creep | PowerCreep`.")
w("class IsCreep :: Type -> Constraint")
w("class IsRoomObject a <= IsCreep a")
w("")
w("-- | `RoomPosition` or anything with a `pos` (every RoomObject). The JS API accepts both.")
w("class HasPos :: Type -> Constraint")
w("class HasPos a")
w("")
w("-- | Types with a global JS constructor of the given name, used by `downcast`.")
w("class IsRoomObject a <= RoomObjectClass a where")
w("  className :: Proxy a -> String")
w("")

def inst(cls, t):
    w(f"instance {cls[0].lower() + cls[1:]}{t} :: {cls} {t}")

w("instance hasPosRoomPosition :: HasPos RoomPosition")
for t in ABSTRACT + ["AnyCreep"] + concrete:
    inst("IsRoomObject", t)
    inst("HasPos", t)
    if t == "AnyCreep":
        inst("IsCreep", t)
        continue
    anc = [t] + chain(t)
    if "Structure" in anc:
        inst("IsStructure", t)
    if "OwnedStructure" in anc:
        inst("IsOwnedStructure", t)
    if t in ("Creep", "PowerCreep"):
        inst("IsCreep", t)
    w(f'instance roomObjectClass{t} :: RoomObjectClass {t} where className _ = "{t}"')
w("")
w("-- | Treat any RoomObject as a plain `RoomObject`. Free at runtime.")
w("toRoomObject :: forall a. IsRoomObject a => a -> RoomObject")
w("toRoomObject = unsafeCoerce")
w("")
w("-- | Treat any structure as a plain `Structure`. Free at runtime.")
w("toStructure :: forall a. IsStructure a => a -> Structure")
w("toStructure = unsafeCoerce")
w("")
w("-- | Treat any owned structure as a plain `OwnedStructure`. Free at runtime.")
w("toOwnedStructure :: forall a. IsOwnedStructure a => a -> OwnedStructure")
w("toOwnedStructure = unsafeCoerce")
w("")
w("-- | Treat a `Creep` or `PowerCreep` as `AnyCreep`. Free at runtime.")
w("toAnyCreep :: forall a. IsCreep a => a -> AnyCreep")
w("toAnyCreep = unsafeCoerce")
w("")
w("foreign import instanceOfImpl :: forall a. Fn2 String a Boolean")
w("")
w("-- | Narrow a mixed value (`RoomObject`, `Structure`, `OwnedStructure`, `AnyCreep`,")
w("-- | e.g. a result of `FIND_STRUCTURES`) to a concrete type with a JS `instanceof`")
w("-- | check: `downcast s :: Maybe StructureTower`.")
w("downcast :: forall a b. IsRoomObject b => RoomObjectClass a => b -> Maybe a")
w("downcast x")
w("  | runFn2 instanceOfImpl (className (Proxy :: Proxy a)) x = Just (unsafeCoerce x)")
w("  | otherwise = Nothing")
open(f"{OUT}/src/Screeps/Types.purs", "w").write("\n".join(L) + "\n")
open(f"{OUT}/src/Screeps/Types.js", "w").write(
    "// Global constructors (Creep, StructureTower, ...) are stable across ticks.\n"
    "export const instanceOfImpl = (name, x) => {\n"
    "  const g = typeof global !== \"undefined\" ? global : globalThis;\n"
    "  const C = g[name];\n"
    "  return typeof C === \"function\" && x instanceof C;\n"
    "};\n")

