for n in names:
    if n in SKIP:
        continue
    v = consts[n]
    if n == "OK" or n.startswith("ERR_"):
        entries.append((camel(n), n, "ReturnCode", "ReturnCode"))
    elif n.startswith("FIND_"):
        entries.append((camel(n), n, f"FindConstant {FIND_T[n]}", "FindConstant"))
    elif n.startswith("LOOK_"):
        entries.append((camel(n), n, f"LookConstant {LOOK_T[n]}", "LookConstant"))
    elif n in DIRS:
        entries.append(("direction" + camel(n)[0].upper() + camel(n)[1:], n, "DirectionConstant", "DirectionConstant"))
    elif n in PARTS:
        entries.append(("bodyPart" + camel(n)[0].upper() + camel(n)[1:], n, "BodyPartConstant", "BodyPartConstant"))
    elif n in INTERSHARD:
        entries.append((camel(n), n, "ResourceConstant", "ResourceConstant"))
    elif n == "POWER_CLASS":
        entries.append(("powerClassOperator", "POWER_CLASS.OPERATOR", "PowerClassConstant", "PowerClassConstant"))
    elif n in OBJ_T:
        entries.append((camel(n), n, OBJ_T[n], "Table"))
    else:
        for pre, t, _ in PREFIX:
            if n.startswith(pre):
                entries.append((camel(n), n, t, t))
                break
        else:
            if isinstance(v, str):
                t = "String"
            elif is_int(v):
                t = "Int"
            elif isinstance(v, (int, float)):
                t = "Number"
            else:
                raise SystemExit(f"unclassified constant {n}: {v!r}")
            entries.append((camel(n), n, t, "Scalar"))

