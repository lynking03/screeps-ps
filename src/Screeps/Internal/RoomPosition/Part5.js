export const inRangeToImpl = (p, target, range) => p.inRangeTo(target, range);
export const inRangeToXYImpl = (p, x, y, range) => p.inRangeTo(x, y, range);
export const isEqualToImpl = (p, target) => p.isEqualTo(target);
export const isEqualToXYImpl = (p, x, y) => p.isEqualTo(x, y);
export const isNearToImpl = (p, target) => p.isNearTo(target);
export const isNearToXYImpl = (p, x, y) => p.isNearTo(x, y);
