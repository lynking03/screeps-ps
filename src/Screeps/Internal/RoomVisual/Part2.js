export const circleImpl = (rv, pos, o) => rv.circle(pos, o);
export const circleXYImpl = (rv, x, y, o) => rv.circle(x, y, o);
export const rectImpl = (rv, pos, w, h, o) => rv.rect(pos, w, h, o);
export const rectXYImpl = (rv, x, y, w, h, o) => rv.rect(x, y, w, h, o);
export const polyImpl = (rv, points, o) => rv.poly(points, o);
